const DICTIONARIES: Record<Locale, Messages> = { th, en };

/** Translate a key for a locale, falling back to the key itself. */
export function translate(locale: Locale, key: string): string {
  return DICTIONARIES[locale][key] ?? DICTIONARIES[DEFAULT_LOCALE][key] ?? key;
}

/** Localized error message for an API error code (falls back to English default). */
export function translateError(locale: Locale, code: ApiErrorCode): string {
  const key = `errors.${code}`;
  const dict = DICTIONARIES[locale];
  return dict[key] ?? ERROR_MESSAGES[code];
}
